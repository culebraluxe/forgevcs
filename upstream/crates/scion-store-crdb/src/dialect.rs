//! SQL portability seam between CockroachDB (the upstream default) and PostgreSQL/Neon
//! (`postgres` feature; `docs/adr/0001-infrastructure-stack.md` §7.1).
//!
//! The SPEC 5.2 schema is the same in both engines once three spellings change: `STRING`
//! becomes `TEXT`, `BYTES` becomes `BYTEA`, and the `unique_rowid()` audit default becomes an
//! identity column. The three `UPSERT`s become `INSERT ... ON CONFLICT ... DO UPDATE` (valid
//! in both, but written once per dialect so the CockroachDB path stays byte-identical to
//! upstream).
//!
//! Two behaviours do not translate and are handled here rather than at call sites:
//!
//! - `AS OF SYSTEM TIME follower_read_timestamp()` has no PostgreSQL equivalent. Stale reads
//!   degrade to strong reads: the [`crate::CrdbMetaStore`] API is unchanged, but on PostgreSQL
//!   reading stale data is an optimisation that is not taken.
//! - The `optimizer_use_forecasts` session option does not exist in PostgreSQL; sending it
//!   makes every connection fail with `unrecognized configuration parameter`.

use std::sync::Arc;

/// Session option that prevents CockroachDB statistics forecasts from turning `ON CONFLICT`
/// arbiters on single-repository tables into whole-repository anti-joins.
pub const NO_FORECASTS: &str = "-c optimizer_use_forecasts=off";

/// Which SQL dialect this crate emits.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Dialect {
    /// CockroachDB (default features; the vendored upstream behaviour).
    Cockroach,
    /// PostgreSQL, including Neon (`postgres` feature).
    Postgres,
}

/// The dialect compiled into this build.
#[cfg(feature = "postgres")]
pub const ACTIVE: Dialect = Dialect::Postgres;
/// The dialect compiled into this build.
#[cfg(not(feature = "postgres"))]
pub const ACTIVE: Dialect = Dialect::Cockroach;

impl Dialect {
    /// Clause inserted between the head and tail of a read statement for
    /// `Consistency::Stale`. PostgreSQL has no follower-read hint, so the clause is a single
    /// space: the stale statement is then byte-identical to the strong one.
    pub const fn stale_read_clause(self) -> &'static str {
        match self {
            Self::Cockroach => " AS OF SYSTEM TIME follower_read_timestamp() ",
            Self::Postgres => " ",
        }
    }

    /// Startup-packet `options`, or `None` when the server would reject them.
    pub const fn session_options(self) -> Option<&'static str> {
        match self {
            Self::Cockroach => Some(NO_FORECASTS),
            Self::Postgres => None,
        }
    }

    /// Bounded retry budget for serialization failures. CockroachDB's lock-based conflicts
    /// converge quickly, so the upstream bound of 10 stays. PostgreSQL's SSI aborts
    /// transactions that merely read a range another transaction appended to, so a run with 32
    /// concurrent writers needs headroom: every loser consumes one attempt.
    pub const fn max_attempts(self) -> u32 {
        match self {
            Self::Cockroach => 10,
            Self::Postgres => 64,
        }
    }

    /// Rewrite one embedded migration for this dialect. Only type spellings and the audit
    /// sequence default change; every statement stays idempotent.
    pub fn migration(self, sql: &'static str) -> String {
        match self {
            Self::Cockroach => sql.to_owned(),
            Self::Postgres => sql
                .replace("DEFAULT unique_rowid()", "GENERATED BY DEFAULT AS IDENTITY")
                .replace("STRING", "TEXT")
                .replace("BYTES", "BYTEA"),
        }
    }

    /// The `UNNEST` cast spelling for text arrays in the batched inserts.
    pub const fn text_array_cast(self) -> &'static str {
        match self {
            Self::Cockroach => "STRING[]",
            Self::Postgres => "TEXT[]",
        }
    }

    /// The `UNNEST` cast spelling for byte arrays in the batched inserts.
    pub const fn bytes_array_cast(self) -> &'static str {
        match self {
            Self::Cockroach => "BYTES[]",
            Self::Postgres => "BYTEA[]",
        }
    }
}

/// Adapt an inline statement literal to the active dialect. Only the array element casts used
/// by the batched `UNNEST` inserts differ (`::STRING[]`/`::BYTES[]` in CockroachDB,
/// `::TEXT[]`/`::BYTEA[]` in PostgreSQL); every other statement is dialect-neutral and is
/// returned borrowed, so the CockroachDB path prepares exactly the upstream text.
pub fn adapt_inline_sql(sql: &str) -> std::borrow::Cow<'_, str> {
    use std::borrow::Cow;
    if ACTIVE == Dialect::Postgres && (sql.contains("::STRING[]") || sql.contains("::BYTES[]")) {
        Cow::Owned(
            sql.replace("::STRING[]", "::TEXT[]")
                .replace("::BYTES[]", "::BYTEA[]"),
        )
    } else {
        Cow::Borrowed(sql)
    }
}

/// A rustls client configuration trusting the webpki roots. Neon rejects unencrypted
/// connections, so the `postgres` build supplies this wherever a connection is opened and no
/// caller-provided configuration exists (tests, `connect_fresh_for_tests`).
#[cfg(feature = "postgres")]
pub fn tls_client_config() -> Option<Arc<rustls::ClientConfig>> {
    let mut roots = rustls::RootCertStore::empty();
    roots.extend(webpki_roots::TLS_SERVER_ROOTS.iter().cloned());
    let provider = Arc::new(rustls::crypto::ring::default_provider());
    let config = rustls::ClientConfig::builder_with_provider(provider)
        .with_safe_default_protocol_versions()
        .ok()?
        .with_root_certificates(roots)
        .with_no_client_auth();
    Some(Arc::new(config))
}

/// TLS for the test harness: required by PostgreSQL, unused (and `None`) for CockroachDB,
/// whose tests connect over plaintext.
pub fn test_tls() -> Option<Arc<rustls::ClientConfig>> {
    #[cfg(feature = "postgres")]
    {
        tls_client_config()
    }
    #[cfg(not(feature = "postgres"))]
    {
        None
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn postgres_migrations_use_portable_type_names() {
        for &(name, sql) in crate::MIGRATIONS {
            let ported = Dialect::Postgres.migration(sql);
            assert!(!ported.contains("BYTES"), "{name} still uses BYTES");
            assert!(!ported.contains("STRING"), "{name} still uses STRING");
            assert!(
                !ported.contains("unique_rowid"),
                "{name} still uses unique_rowid()"
            );
        }
    }

    #[test]
    fn postgres_migrations_keep_every_column() {
        let ported = Dialect::Postgres.migration(crate::MIGRATIONS[0].1);
        assert!(ported.contains("object_id    BYTEA NOT NULL"));
        assert!(ported.contains("BYTEA[] NOT NULL"), "changesets.skip");
        assert!(
            ported.contains("GENERATED BY DEFAULT AS IDENTITY"),
            "audit_log.seq"
        );
        assert!(ported.contains("name        TEXT NOT NULL"), "repos.name");
        assert_eq!(
            ported.matches("CREATE TABLE").count(),
            crate::MIGRATIONS[0].1.matches("CREATE TABLE").count()
        );
    }

    #[test]
    fn cockroach_migrations_are_untouched() {
        for &(_, sql) in crate::MIGRATIONS {
            assert_eq!(Dialect::Cockroach.migration(sql), sql);
        }
    }

    #[test]
    fn stale_reads_degrade_to_strong_reads_on_postgres() {
        assert_eq!(Dialect::Postgres.stale_read_clause(), " ");
        assert_eq!(
            Dialect::Cockroach.stale_read_clause(),
            " AS OF SYSTEM TIME follower_read_timestamp() "
        );
        assert!(Dialect::Postgres.session_options().is_none());
        assert_eq!(Dialect::Cockroach.session_options(), Some(NO_FORECASTS));
        assert_eq!(Dialect::Postgres.text_array_cast(), "TEXT[]");
        assert_eq!(Dialect::Postgres.bytes_array_cast(), "BYTEA[]");
    }
}
